    %% Update Scenario

    function updateScenario()

        marital = maritalDropdown.Value;
        dependents = dependentsDropdown.Value;

        % Show or hide spouse information
        % Show or hide spouse information
        if strcmp(marital, 'Married')

            spousePanel.Visible = 'on';

            % Show spouse retirement assumption
            spouseLifespanLabel.Visible = 'on';
            spouseLifespanField.Visible = 'on';

        else

            spousePanel.Visible = 'off';

            % Hide spouse retirement assumption
            spouseLifespanLabel.Visible = 'off';
            spouseLifespanField.Visible = 'off';

        end
        % Show or hide dependent information
        if strcmp(dependents, 'Yes')
            dependentPanel.Visible = 'on';
        else
            dependentPanel.Visible = 'off';
        end

        % Identify household scenario
        if strcmp(marital, 'Single')

            if strcmp(dependents, 'Yes')
                scenario = 'Single with Dependents';
            else
                scenario = 'Single without Dependents';
            end

        else

            if strcmp(dependents, 'Yes')
                scenario = 'Married with Dependents';
            else
                scenario = 'Married without Dependents';
            end

        end

        scenarioLabel.Text = ['Scenario: ', scenario];

    end



%% Collect User Information

    function continueApplication()

        marital = maritalDropdown.Value;
        dependents = dependentsDropdown.Value;

        currentAge = ageField.Value;
        annualIncome = incomeField.Value;

        % Retirement assumptions
        lifespan = lifespanField.Value;
        % Default: no spouse
        spouseLifespan = NaN;

        if strcmp(marital, 'Married')
            spouseLifespan = spouseLifespanField.Value;
        end

        discountRate = discountField.Value / 100;
        colaRate = colaField.Value / 100;

        spouseAge = NaN;
        spouseIncome = NaN;
        numberDependents = 0;
        youngestDependentAge = NaN;

        if strcmp(marital, 'Married')
            spouseAge = spouseAgeField.Value;
            spouseIncome = spouseIncomeField.Value;
        end

        if strcmp(dependents, 'Yes')
            numberDependents = dependentCountField.Value;
            youngestDependentAge = dependentAgeField.Value;
        end

        userData = struct( ...
            'maritalStatus', marital, ...
            'hasDependents', dependents, ...
            'currentAge', currentAge, ...
            'annualIncome', annualIncome, ...
            'spouseAge', spouseAge, ...
            'spouseIncome', spouseIncome, ...
            'numberDependents', numberDependents, ...
            'youngestDependentAge', youngestDependentAge, ...
            'lifespan', lifespan, ...
            'spouseLifespan', spouseLifespan, ...
            'discountRate', discountRate, ...
            'colaRate', colaRate);

        disp(userData);

        % Run optimization and handle errors
        try
            showResults(userData);
        catch ME
            uialert(fig, ME.message, ...
                'Unable to Calculate Results');
            return;
        end

        % Enable the Results button
        resultsButton.Enable = 'on';

        % Switch to Results page
        switchPage('results');

    end

    %% Results Dashboard

    function showResults(userData)

        %% Step 1: Model Assumptions

        lifespan = userData.lifespan;
        spouseLifespan = userData.spouseLifespan;

        discountRate = userData.discountRate;
        colaRate = userData.colaRate;

        isMarried = strcmp(userData.maritalStatus, 'Married');
        hasDependents = strcmp(userData.hasDependents, 'Yes');

        % Validate supported age range
        if userData.currentAge >= lifespan
            error('Your lifespan must exceed your current age.');
        end

        if isMarried && userData.spouseAge >= spouseLifespan
            error('Spouse lifespan must exceed spouse current age.');
        end



        %% Step 2: Run Household Optimization

        % Run the model for the selected household
        result = optimizeHousehold(userData);

        % Retrieve maximum household NPV
        maxNPV = result.maxNPV;

        if isMarried

            % Married household results
            optimalAge1 = result.optimalAge1;
            optimalAge2 = result.optimalAge2;

            ages1 = result.ages1;
            ages2 = result.ages2;
            npvMatrix = result.npvMatrix;

            ageText = sprintf('You: %d | Spouse: %d', ...
                optimalAge1, optimalAge2);

        else

            % Single household results
            optimalAge = result.optimalAge1;

            claimingAges = result.ages1;
            npvValues = result.npvMatrix(:)';

            ageText = sprintf('%d years old', optimalAge);

        end


        %% Step 3: Clear Previous Results

        delete(resultsTab.Children);


        %% Step 4: Main Dashboard Layout

        mainGrid = uigridlayout(resultsTab, [3 2]);

        mainGrid.RowHeight = {105, 105, '1x'};
        mainGrid.ColumnWidth = {'1x', '1x'};
        mainGrid.Padding = [25 25 25 25];
        mainGrid.RowSpacing = 20;
        mainGrid.ColumnSpacing = 20;
        mainGrid.BackgroundColor = colors.background;


        %% Step 5: Household Summary

        summaryPanel = uipanel(mainGrid, ...
            'Title', 'Household Summary', ...
            'FontSize', 15, ...
            'FontWeight', 'bold', ...
            'ForegroundColor', colors.text, ...
            'BackgroundColor', colors.card);

        summaryPanel.Layout.Row = 1;
        summaryPanel.Layout.Column = [1 2];

        scenario = userData.maritalStatus;

        if hasDependents
            scenario = [scenario, ' with Dependents'];
        else
            scenario = [scenario, ' without Dependents'];
        end

        uilabel(summaryPanel, ...
            'Text', ['Scenario: ', scenario], ...
            'FontSize', 14, ...
            'FontWeight', 'bold', ...
            'FontColor', colors.accent, ...
            'Position', [20 60 900 25]);

        summaryText = sprintf( ...
            'Age: %.0f | Annual Income: $%.0f', ...
            userData.currentAge, ...
            userData.annualIncome);

        if isMarried

            summaryText = sprintf( ...
                '%s | Spouse Age: %.0f | Spouse Income: $%.0f', ...
                summaryText, ...
                userData.spouseAge, ...
                userData.spouseIncome);

        end

        uilabel(summaryPanel, ...
            'Text', summaryText, ...
            'FontSize', 12, ...
            'FontColor', colors.secondary, ...
            'Position', [20 20 950 30]);


        %% Step 6: Optimal Claiming Age

        agePanel = uipanel(mainGrid, ...
            'Title', 'Optimal Claiming Age', ...
            'FontSize', 14, ...
            'FontWeight', 'bold', ...
            'ForegroundColor', colors.text, ...
            'BackgroundColor', colors.card);

        agePanel.Layout.Row = 2;
        agePanel.Layout.Column = 1;

        uilabel(agePanel, ...
            'Text', ageText, ...
            'FontSize', 20, ...
            'FontWeight', 'bold', ...
            'FontColor', colors.accent, ...
            'Position', [20 25 440 45]);


        %% Step 7: Maximum Net Present Value

        benefitsPanel = uipanel(mainGrid, ...
            'Title', 'Maximum Net Present Value', ...
            'FontSize', 14, ...
            'FontWeight', 'bold', ...
            'ForegroundColor', colors.text, ...
            'BackgroundColor', colors.card);

        benefitsPanel.Layout.Row = 2;
        benefitsPanel.Layout.Column = 2;

        uilabel(benefitsPanel, ...
            'Text', sprintf('$%.2f', maxNPV), ...
            'FontSize', 22, ...
            'FontWeight', 'bold', ...
            'FontColor', colors.accent, ...
            'Position', [20 25 440 45]);


        %% Step 8: Graph Panel

        graphPanel = uipanel(mainGrid, ...
            'Title', 'Lifetime Benefits Analysis', ...
            'FontSize', 14, ...
            'FontWeight', 'bold', ...
            'ForegroundColor', colors.text, ...
            'BackgroundColor', colors.card);

        graphPanel.Layout.Row = 3;
        graphPanel.Layout.Column = [1 2];

        graphGrid = uigridlayout(graphPanel, [2 1]);
        graphGrid.RowHeight = {'1x', 35};
        graphGrid.Padding = [15 8 15 8];
        graphGrid.RowSpacing = 4;
        graphGrid.BackgroundColor = colors.card;

        ax = uiaxes(graphGrid);
        ax.Layout.Row = 1;

        % Graph appearance
        ax.Color = [0.10 0.14 0.21];

        ax.XColor = [0.90 0.93 0.98];
        ax.YColor = [0.90 0.93 0.98];

        ax.GridColor = [0.65 0.72 0.82];
        ax.GridAlpha = 0.25;

        ax.FontSize = 12;
        ax.FontWeight = 'bold';

        ax.Box = 'on';
        ax.LineWidth = 1.2;


        %% Step 9: Generate Visualization

        if isMarried

            % Married Couple Heatmap

            imagesc(ax, ages2, ages1, npvMatrix);

            ax.YDir = 'normal';

            % Use high-contrast colors
            colormap(ax, turbo(256));

            % Add a colorbar
            cb = colorbar(ax);
            cb.Color = colors.text;
            cb.FontSize = 11;
            cb.Label.String = 'Household NPV ($)';
            cb.Label.Color = colors.text;
            hold(ax, 'on');

            plot(ax, optimalAge2, optimalAge1, 'p', ...
                'MarkerSize', 20, ...
                'MarkerEdgeColor', [0 0 0], ...
                'MarkerFaceColor', [1 1 1], ...
                'LineWidth', 1.5);

            hold(ax, 'off');

            xticks(ax, ages2);
            yticks(ax, ages1);

            xlabel(ax, 'Spouse Claiming Age', ...
                'Color', colors.secondary);

            ylabel(ax, 'Your Claiming Age', ...
                'Color', colors.secondary);

            title(ax, 'Household NPV by Claiming Ages', ...
                'Color', colors.text);

        else


            % Single Individual Line Chart

            plot(ax, claimingAges, npvValues, '-o', ...
                'LineWidth', 3, ...
                'Color', [0.25 0.75 1.00], ...
                'MarkerSize', 7, ...
                'MarkerFaceColor', [0.25 0.75 1.00]);

            hold(ax, 'on');

            % Highlight optimal claiming age
            plot(ax, optimalAge, maxNPV, 'p', ...
                'MarkerSize', 18, ...
                'MarkerEdgeColor', [1.00 0.80 0.20], ...
                'MarkerFaceColor', [1.00 0.80 0.20]);

            hold(ax, 'off');

            xticks(ax, claimingAges);

            % Add padding around plotted values
            yPadding = max(1, 0.10 * range(npvValues));

            ylim(ax, [min(npvValues) - yPadding, ...
                max(npvValues) + yPadding]);

            xlabel(ax, 'Claiming Age', ...
                'Color', colors.text, ...
                'FontSize', 12);

            ylabel(ax, 'Net Present Value ($)', ...
                'Color', colors.text, ...
                'FontSize', 12);

            title(ax, 'NPV by Claiming Age', ...
                'Color', colors.text, ...
                'FontSize', 14);

            grid(ax, 'on');


        end


        %% Step 10: Display Model Assumptions


        %% Step 10: Display Model Assumptions

        if isMarried

            note = sprintf( ...
                ['Lifespans: %d / %d | Discount: %.1f%% | ' ...
                'COLA: %.1f%%'], ...
                lifespan, spouseLifespan, ...
                discountRate * 100, colaRate * 100);

        else

            note = sprintf( ...
                'Lifespan: %d | Discount: %.1f%% | COLA: %.1f%%', ...
                lifespan, ...
                discountRate * 100, ...
                colaRate * 100);

        end

        % Explain simplified household benefits
        if isMarried
            note = [note, ...
                ' | Approximate spousal benefits included.'];
        end

        if hasDependents
            note = [note, ...
                ' | Approximate child benefits included.'];
        end

        % Model limitation
        note = [note, ...
            ' | Classroom model, not an official SSA estimate.'];

        % Display note underneath the graph
        modelNote = uilabel(graphGrid, ...
            'Text', note, ...
            'FontColor', colors.secondary, ...
            'FontSize', 10, ...
            'WordWrap', 'on', ...
            'HorizontalAlignment', 'center');

        modelNote.Layout.Row = 2;

    end

    function switchPage(page)

        if strcmp(page, 'household')

            householdTab.Visible = 'on';
            resultsTab.Visible = 'off';

            householdButton.BackgroundColor = colors.accent;
            resultsButton.BackgroundColor = colors.card;

        elseif strcmp(page, 'results')

            householdTab.Visible = 'off';
            resultsTab.Visible = 'on';

            householdButton.BackgroundColor = colors.card;
            resultsButton.BackgroundColor = colors.accent;

        end

    end

    %% Initialize GUI

    updateScenario();

end
